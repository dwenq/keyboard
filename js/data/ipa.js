/**
 * 取单词的国际音标（不区分大小写）。
 * @param {string} word 英文单词
 * @returns {string} 音标字符串（含斜杠包裹），未收录时返回空字符串
 */
window.ipaOf = function (word) {
  const w = String(word || "").trim();
  if (!w) return "";
  if (window.IPA_MAP[w]) return window.IPA_MAP[w];
  const low = w.toLowerCase();
  if (window.IPA_MAP[low]) return window.IPA_MAP[low];
  // 兜底：对词典键做不区分大小写的扫描匹配，处理如 Monday/Monday 这类键。
  for (const k in window.IPA_MAP) {
    if (k.toLowerCase() === low) return window.IPA_MAP[k];
  }
  return "";
};
